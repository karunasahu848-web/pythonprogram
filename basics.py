# DATA TYPES
# 1. int -> integers 
a = 34
print(type(a))
# 2. float -> decimal numbers
b = 1.33
print(type(b))
# 3. str -> string (text)
c = 'Hello World "12345@#$%" '
print(type(c))
# 4. bool -> boolean (True or False)
d = False
print(type(d))
# 5. complex -> imaginary nums
e = 12 + 4j 
print(type(e))
